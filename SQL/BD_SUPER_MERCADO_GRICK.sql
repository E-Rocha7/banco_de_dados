/* CONSULTAR COMO SERIA AUMENTAR EM R$ 2,00 O PREÇO DOS PRODUTOS
COM O PREÇO ATUAL ACIMA DE R$ 5,00*/
SELECT  PRO_NOME AS "NOME",
		PRO_PRECO AS "PREÇO ATUAL",
        (PRO_PRECO+2) AS "PREÇO COM AUMENTO"
FROM 	PRODUTO
WHERE 	PRO_PRECO > 5;

/*CONSULTAR COM SERIA DIMINUIR EM 1R$ O PREÇO DOS PRODUTOS COM PREÇO ATUAL ABAIXO (MENOR) DE 5R$*/

SELECT  PRO_NOME AS "NOME",
		PRO_PRECO AS "PREÇO ATUAL",
        (PRO_PRECO-1) AS "PREÇO COM DESCONTO"
FROM 	PRODUTO
WHERE 	PRO_PRECO < 5;

/*CONSULTAR COMO SERIA APLICAR UM DESCONTO DE 10% PARA TODOS OS PRODUTOS*/

SELECT PRO_NOME AS "NOME DO PRODUTO",
	   PRO_PRECO AS "PREÇO ATUAL",
       PRO_PRECO - (PRO_PRECO * 0.1) AS "PREÇO COM DESCONTO"
FROM   PRODUTO;

/*ATUALIZAR O ESTOQUE DO ARROZ DIVIDINDO PELA METADE*/

SELECT * FROM PRODUTO;

UPDATE PRODUTO
SET    PRO_QUANTIDADE = PRO_QUANTIDADE / 2
WHERE  PRO_ID = 1;

/*CONSULTAR TODOS OS PRODUTOS QUE TENHAM DATA DE VALIDADE
ENTRE SET/2024 E DEZ/2024*/
SELECT PRO_NOME AS "NOME DO PRODUTO",
	   PRO_DATA_VALIDADE AS "DATA DE VALIDADE"
FROM   PRODUTO
WHERE  PRO_DATA_VALIDADE BETWEEN '2024-09-01' AND '2024-12-31';

/*CONSULTAR TODOS OS PRODUTOS QUE TENHAM PREÇO MAIOR QUE R$10 OU PREÇO MENOR QUE R$ 4 */

SELECT PRO_NOME AS "NOME",
	   PRO_PRECO AS "PREÇO DO PRODUTO"
FROM   PRODUTO
WHERE PRO_PRECO > 10 OR PRO_PRECO < 5;

/*CONSULTAR OS DDS E TELEFONES DOS CONSUMIDORES SEPARADAMENTE*/
SELECT CON_NOME AS "NOME DO CONSUMIDOR",
	   SUBSTRING(CON_TELEFONE, 1, 2) AS "DDD DE TELEFONE",
       SUBSTRING(CON_TELEFONE, 3, 11) AS "TELEFONE"
FROM   CONSUMIDOR;

/*CONSULTAR OS DADOS DO SUPERMERCADO "JUNTANDO" DUAS COLUNAS*/
SELECT SUP_RAZAO_SOCIAL AS "NOME DO SUPERMERCADO",
	   CONCAT(SUP_ENDERECO_LOGRADOURO,
       CONCAT(",",
       CONCAT(SUP_ENDERECO_NUMERO,
       CONCAT(",", 
       CONCAT(SUP_ENDERECO_CIDADE,
       CONCAT(" - ", SUP_ENDERECO_ESTADO)))))) AS "ENDEREÇO"
       
FROM SUPERMERCADO;

/*GERAR UMA CONSULTA PARA VERIFICAR O STATUS DO ESTOQUE
DOS PRODUTOS, CONSIDERANDO:
	QUANTIDADE <= 25: ESTOQUE BAIXO
    QUANTIDADE > 25 E QUANTIDADE <=100: ESTOQUE MÉDIO
    QUANTIDADE > 100: ESTOQUE ALTO*/
    
SELECT PRO_NOME AS "NOME DO PRODUTO",
		PRO_QUANTIDADE AS "QUANTIDADE EM ESTOQUE",
        CASE
			WHEN PRO_QUANTIDADE <= 25 THEN "ESTOQUE BAIXO"
            WHEN PRO_QUANTIDADE > 25 AND PRO_QUANTIDADE <=100 THEN "ESTOQUE MÉDIO"
            WHEN PRO_QUANTIDADE > 100 THEN "ESTOQUE ALTO"
            END AS "NIVEL DO ESTOQUE"
FROM 	PRODUTO;

/*CONTAR QUANTOS CONSUMIDORES TEM O SUPERMERCADO*/
SELECT COUNT(CON_CPF) AS "QUANTIDADE DE CONSUMIDORES"
FROM CONSUMIDOR;
/*SOMAR O VALOR DE TODOS OS PRODUTOS DO SUPERMERCADO*/
SELECT CONCAT("R$",
CONCAT( SUM(PRO_PRECO), "00")) AS "PREÇO TOTAL DOS PRODUTOS"
FROM PRODUTO;

